const { generateResponse } = require('./llm-client');
// '../memory/memory-store' is one directory up, then into the memory directory.
const { appendMemory, saveMemory, getMemoryEntries } = require('../memory/memory-store'); 
const { log, error } = require('./logger');

// Note: We are not calling loadMemory() here. It's assumed that the entry point (index.js)
// will call loadMemory() once at startup to populate the in-memory store.

/**
 * Executes a single cycle of the agent's operation.
 * This involves taking user input, getting a response from the LLM,
 * creating a memory entry for the interaction, and saving the memory.
 * * @param {string} userInput - The text input provided by the user.
 * @returns {Promise<string>} The text response generated by the LLM.
 * @throws {Error} If the user input is invalid, LLM generation fails, or memory operations
 * encounter an issue.
 */
async function runAgentCycle(userInput) {
  // Basic validation for user input.
  if (!userInput || typeof userInput !== 'string' || userInput.trim() === '') {
    throw new Error("Invalid user input provided for agent cycle. Input cannot be empty.");
  }

  try {
    // 1. Generate a response from the LLM using the user's input.
    // We pass the user's input directly as the prompt for this basic chat.
    log(`Agent loop: Requesting LLM response for: "${userInput}"`);
    const llmResponse = await generateResponse(userInput);
    log(`Agent loop: Received response from LLM.`);

    // 2. Prepare the data for a new memory entry.
    // For this v0.1, we're using default values for scope, type, and empty entities.
    // These will become more dynamic in future iterations.
    const memoryEntryData = {
      user_input: userInput,
      llm_response: llmResponse,
      thematic_scope: 'general_chat', // Default scope for simple chat interactions
      event_type: 'chat_turn',        // Indicates this interaction was a turn in a chat
      entities: []                    // No specific entities extracted in this basic chat turn
    };

    // 3. Append the new memory entry to the in-memory store.
    // The appendMemory function will handle ID generation and validation.
    const addedEntry = appendMemory(memoryEntryData);

    // If appendMemory returns null, it means validation failed.
    if (!addedEntry) {
      // The appendMemory function already logs an error, so we just throw a general failure.
      throw new Error("Failed to append a valid memory entry. Check logs for details.");
    }

    // 4. Save the entire memory store to disk.
    // This ensures persistence after each successful interaction.
    await saveMemory();

    // 5. Return the LLM's response. This will be displayed to the user.
    return llmResponse;

  } catch (e) {
    error(`Agent Cycle Error: ${e.message}`);
    // Re-throw the error to be caught and handled by the entry point (e.g., index.js).
    // This allows the entry point to inform the user about the failure.
    throw e;
  }
}

// Export the runAgentCycle function so it can be called from the entry point.
module.exports = {
  runAgentCycle,
  // Future enhancements might include functions to retrieve memories here,
  // but for v0.1, memory retrieval is handled by memory-store.js and accessed by index.js
};