// agent/core/agent-loop.js

// Import necessary modules from other parts of the agent.
const { generateResponse } = require('./llm-client');
const { appendMemory, saveMemory } = require('../memory/memory-store'); 
// Import our new intent extractor function.
const { extractIntentAndEntities } = require('./intent-extractor');
// Import the new retriever and the finance API tool
const { retrieveRelevantMemories } = require('../memory/memory-retriever');
const { fetchStockPrice } = require('../data_sources/finance_api');
const { fetchNews } = require('../data_sources/news_api');

/**
 * Executes a single cycle of the agent's operation. This now includes intent extraction.
 * 
 * @param {string} userInput - The text input provided by the user.
 * @returns {Promise<string>} The text response generated by the LLM for the user.
 * @throws {Error} If any step in the cycle fails.
 */
async function runAgentCycle(userInput) {
  // Basic validation for user input.
  if (!userInput || typeof userInput.trim() !== 'string' || userInput.trim() === '') {
    throw new Error("Invalid user input provided for agent cycle. Input cannot be empty.");
  }

  try {
    // 1. Understand Intent: Extract intent from the current query *first* to decide what to do.
    console.log(`Agent loop: Extracting intent from query: "${userInput}"`);
    const initialIntent = await extractIntentAndEntities(userInput, "");

    let llmResponse;
    let contextForMemory = {}; // Holds data fetched from tools, to be saved in memory.
    let augmentedPrompt = userInput; // Default prompt is just the user's input.

    // 2. Decide Action: Prioritize tool use (data_request or news_request) over memory retrieval.
    if (initialIntent.event_type === 'data_request' && initialIntent.entities.some(e => e.type === 'STOCK_TICKER')) {
      // --- Tool Use Path: Fetch Stock Price ---
      console.log('Agent loop: Detected a data request for stock price. Using finance tool...');
      const tickerEntity = initialIntent.entities.find(e => e.type === 'STOCK_TICKER');
      if (tickerEntity) {
        const price = await fetchStockPrice(tickerEntity.value);
        if (price !== null) {
          contextForMemory.price = price; // Store fetched data in context for memory.
          // Augment the prompt with the live data.
          augmentedPrompt = `The user asked: "${userInput}". Using the data I found: The live price of ${tickerEntity.value} is $${price}. Formulate a natural language response.`;
        }
      }
    } else if (initialIntent.event_type === 'news_request' && initialIntent.entities.some(e => e.type === 'STOCK_TICKER')) {
      // --- Tool Use Path: Fetch News ---
      console.log('Agent loop: Detected a news request. Using news tool...');
                          const tickerEntity = initialIntent.entities.find(e => e.type === 'STOCK_TICKER');
                          if (tickerEntity) {
                            let fromDateTime = null;
                            let toDateTime = null;
                
                            const fromEntity = initialIntent.entities.find(e => e.type === 'DATE_FROM');
                            const toEntity = initialIntent.entities.find(e => e.type === 'DATE_TO');
                
                            if (fromEntity && toEntity) {
                              fromDateTime = fromEntity.value;
                              toDateTime = toEntity.value;
                              console.log(`Agent loop: Fetching news from ${fromDateTime} to ${toDateTime}`);
                            } else {
                              // Default to the last 24 hours if no specific date range is provided
                              const now = new Date();
                              const twentyFourHoursAgo = new Date(now.getTime() - (24 * 60 * 60 * 1000));
                
                              // Format dates to YYYYMMDDTHHMM
                              const formatDateTime = (date) => {
                                return date.toISOString().replace(/[-:]|\..+/g, '').slice(0, 13);
                              };
                
                              fromDateTime = formatDateTime(twentyFourHoursAgo);
                              toDateTime = formatDateTime(now);
                              console.log(`Agent loop: Fetching latest news (last 24 hours)`);
                            }
                
            const newsArticles = await fetchNews(tickerEntity.value, { from: fromDateTime, to: toDateTime, limit: 5 });
            if (newsArticles && newsArticles.length > 0) {
              contextForMemory.news = newsArticles; // Store fetched data in context for memory.
              
              // Process sentiment data
              let totalSentimentScore = 0;
              let sentimentCounts = { 'Positive': 0, 'Negative': 0, 'Neutral': 0, 'Mixed': 0 };
              const articleSummaries = [];

              newsArticles.forEach(article => {
                totalSentimentScore += parseFloat(article.overall_sentiment_score);
                if (article.overall_sentiment_label) {
                  sentimentCounts[article.overall_sentiment_label]++;
                }
                articleSummaries.push({
                  title: article.title,
                  url: article.url,
                  summary: article.summary,
                  sentiment_score: article.overall_sentiment_score,
                  sentiment_label: article.overall_sentiment_label
                });
              });

              const averageSentimentScore = newsArticles.length > 0 ? (totalSentimentScore / newsArticles.length).toFixed(2) : 'N/A';
              const sentimentDistribution = Object.entries(sentimentCounts)
                .filter(([label, count]) => count > 0)
                .map(([label, count]) => `${count} ${label}`)
                .join(', ');

              const articlesForLLMSummary = articleSummaries.map(art => 
                `- Title: ${art.title}\nSummary: ${art.summary}\nURL: ${art.url}\nSentiment: ${art.sentiment_label} (${art.sentiment_score})`
              ).join('\n\n');

              const summarizationPrompt = `
                The user is asking about news for ${tickerEntity.value} from ${fromDateTime} to ${toDateTime}.
                I have retrieved the following news articles, including their titles, summaries, URLs, and sentiment analysis:
                ${articlesForLLMSummary}

                Overall Sentiment: The average sentiment score is approximately ${averageSentimentScore}. The distribution of sentiment labels is: ${sentimentDistribution}.

                Please provide a concise summary of these news articles, highlighting any key takeaways or significant developments related to ${tickerEntity.value}. Critically, incorporate the sentiment analysis into your summary. For example, mention if the overall sentiment is positive or negative, and point out any particularly bullish or bearish articles that stand out. Focus on what's most relevant to a financial researcher.
              `;

              const llmNewsSummary = await generateResponse(summarizationPrompt);

              augmentedPrompt = `The user asked: "${userInput}". Here is a summary of the news and its sentiment for ${tickerEntity.value} from ${fromDateTime} to ${toDateTime}:\n\n${llmNewsSummary}\n\nFormulate a natural language response based on this summary.`;
            } else {
              augmentedPrompt = `The user asked: "${userInput}". I could not find any news for ${tickerEntity.value} from ${fromDateTime} to ${toDateTime}. Please inform the user.`;
            }
          }
    }

    // --- Memory Retrieval Path ---
    // 3. Retrieve Context: If not a tool request, retrieve relevant past memories.
    console.log('Agent loop: Retrieving relevant memories...');
    const relevantMemories = retrieveRelevantMemories(initialIntent);

    if (relevantMemories.length > 0) {
      // 4. Augment Prompt: Build a context string from the retrieved memories.
      let contextString = "You are a helpful financial research assistant. Use the 'Previous Context' below to inform your answer to the 'Current User Query'.\n\n--- Previous Context ---\n";
      for (const mem of relevantMemories) {
        contextString += `- User asked: "${mem.user_input}"\n- You responded: "${mem.llm_response.substring(0, 150)}..."\n\n`;
      }
      contextString += "--- End of Previous Context ---\n\n";
      // Create the final augmented prompt.
      augmentedPrompt = `${contextString}--- Current User Query ---\n${userInput}`;
    }

    // 5. Generate Response: Call the LLM with the final prompt (either augmented or original).
    console.log(`Agent loop: Generating response with final prompt...`);
    llmResponse = await generateResponse(augmentedPrompt);
    console.log(`Agent loop: Received final response from LLM.`);

    // 6. Save to Memory: Prepare the data for the memory entry.
    const memoryEntryData = {
      user_input: userInput,
      llm_response: llmResponse,
      thematic_scope: initialIntent.thematic_scope,
      event_type: initialIntent.event_type,
      entities: initialIntent.entities,
      context: contextForMemory // Save any data that was fetched from tools.
    };

    // 7. Persist Memory
    const addedEntry = appendMemory(memoryEntryData);
    if (!addedEntry) {
      throw new Error("Failed to append a valid memory entry. Check logs for details.");
    }
    await saveMemory();

    // 8. Return the final response to the UI.
    return llmResponse;

  } catch (error) {
    console.error(`Agent Cycle Error: ${error.message}`);
    // Re-throw the error so it can be caught and handled by the entry point (e.g., index.js).
    throw error;
  } finally {
    console.log("Agent cycle finished.");
  }
}

// Export the updated runAgentCycle function.
module.exports = {
  runAgentCycle,
};
