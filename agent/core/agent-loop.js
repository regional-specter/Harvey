const { generateResponse } = require('./llm-client');
const { appendMemory, saveMemory } = require('../memory/memory-store'); 
// Import our new intent extractor function.
const { extractIntentAndEntities } = require('./intent-extractor');
// Import the new retriever and the finance API tool
const { retrieveRelevantMemories } = require('../memory/memory-retriever');
const { fetchStockPrice } = require('../data_sources/finance_api');
const { fetchNews } = require('../data_sources/news_api');
const { getCik, fetchCompanyFacts, fetchSubmissionMetadata } = require('../data_sources/sec_api');



/**
 * Executes a single cycle of the agent's operation. This now includes intent extraction.
 * 
 * @param {string} userInput - The text input provided by the user.
 * @returns {Promise<string>} The text response generated by the LLM for the user.
 * @throws {Error} If any step in the cycle fails.
 */
async function runAgentCycle(userInput) {
  // Basic validation for user input.
  if (!userInput || typeof userInput.trim() !== 'string' || userInput.trim() === '') {
    throw new Error("Invalid user input provided for agent cycle. Input cannot be empty.");
  }

  const createToolCallMarkdown = (toolName, toolInput, startTime) => {
      const duration = new Date().getTime() - startTime;
      return `\`\`\`tool-output\n` +
          `Tool Used: ${toolName}\n` +
          `Input: ${toolInput}\n` +
          `Duration: ${duration}ms\n` +
          `\`\`\``;
  };

  let contextForMemory = {}; // Holds data fetched from tools, to be saved in memory.
  let augmentedPromptParts = []; // Accumulate parts for the LLM prompt.
  let currentInput = userInput; // The input to use for current intent extraction
  let toolCalledDuringIteration = false; // Flag to track if a tool was called in the current iteration
  let allToolCalls = []; // Array to store all tool calls made during the cycle
  let currentIntent = null;

  // Maximum number of tool iterations to prevent infinite loops
  const MAX_TOOL_ITERATIONS = 5;
  let iterationCount = 0;

  try {
    do {
      toolCalledDuringIteration = false; // Reset for each iteration
      iterationCount++;

      // 1. Understand Intent: Extract intent from the current query.
      console.log(`Agent loop: Extracting intent from query: "${currentInput}"`);
      currentIntent = await extractIntentAndEntities(currentInput, "");

      let toolOutputAddedToPrompt = false; // Flag to track if tool output was added to prompt in this iteration

      // 2. Decide Action: Prioritize tool use (data_request, news_request, earnings_request, filing_request).
      if (currentIntent.event_type === 'data_request' && currentIntent.entities.some(e => e.type === 'STOCK_TICKER')) {
        // --- Tool Use Path: Fetch Stock Price ---
        console.log('Agent loop: Detected a data request for stock price. Using finance tool...');
        const tickerEntity = currentIntent.entities.find(e => e.type === 'STOCK_TICKER');
        if (tickerEntity) {
          const startTime = new Date().getTime();
          const price = await fetchStockPrice(tickerEntity.value);
          const toolCallMarkdown = createToolCallMarkdown('fetchStockPrice', tickerEntity.value, startTime);
          allToolCalls.push({ toolName: 'fetchStockPrice', toolInput: tickerEntity.value, duration: (new Date().getTime() - startTime) });

          if (price !== null) {
            contextForMemory.price = price;
            augmentedPromptParts.push(`The live price of ${tickerEntity.value} is $${price}.`);
          } else {
            augmentedPromptParts.push(`I could not retrieve the live price for ${tickerEntity.value}.`);
          }
          augmentedPromptParts.push(toolCallMarkdown);
          currentInput = `Based on the user's query "${userInput}" and the information I have gathered so far (${augmentedPromptParts.join(' ')}), what should I do next?`;
          toolCalledDuringIteration = true;
          toolOutputAddedToPrompt = true;
        }
      } else if (currentIntent.event_type === 'news_request' && currentIntent.entities.some(e => e.type === 'STOCK_TICKER')) {
        // --- Tool Use Path: Fetch News ---
        console.log('Agent loop: Detected a news request. Using news tool...');
        const tickerEntity = currentIntent.entities.find(e => e.type === 'STOCK_TICKER');
        if (tickerEntity) {
          let fromDateTime = null;
          let toDateTime = null;

          const fromEntity = currentIntent.entities.find(e => e.type === 'DATE_FROM');
          const toEntity = currentIntent.entities.find(e => e.type === 'DATE_TO');

          if (fromEntity && toEntity) {
            fromDateTime = fromEntity.value;
            toDateTime = toEntity.value;
            console.log(`Agent loop: Fetching news from ${fromDateTime} to ${toDateTime}`);
          } else {
            const now = new Date();
            const twentyFourHoursAgo = new Date(now.getTime() - (24 * 60 * 60 * 1000));
            const formatDateTime = (date) => {
              return date.toISOString().replace(/[-:]|\..+/g, '').slice(0, 13);
            };
            fromDateTime = formatDateTime(twentyFourHoursAgo);
            toDateTime = formatDateTime(now);
            console.log(`Agent loop: Fetching latest news (last 24 hours)`);
          }

          const startTime = new Date().getTime();
          const newsArticles = await fetchNews(tickerEntity.value, { from: fromDateTime, to: toDateTime, limit: 5 });
          const toolCallMarkdown = createToolCallMarkdown('fetchNews', tickerEntity.value, startTime);
          allToolCalls.push({ toolName: 'fetchNews', toolInput: tickerEntity.value, duration: (new Date().getTime() - startTime) });
          
          if (newsArticles && newsArticles.length > 0) {
            contextForMemory.news = newsArticles;
            const formattedNews = newsArticles.map(article => {
              const sentimentScore = parseFloat(article.overall_sentiment_score).toFixed(2);
              return `- ${article.title} (Source: ${article.source}) [Sentiment: ${sentimentScore}]`;
            }).join('\n');
            augmentedPromptParts.push(`Here are the relevant news headlines I found for ${tickerEntity.value} from ${fromDateTime} to ${toDateTime}:\n--- News Headlines ---\n${formattedNews}\n---`);
          } else {
            augmentedPromptParts.push(`I could not find any news for ${tickerEntity.value} from ${fromDateTime} to ${toDateTime}.`);
          }
          augmentedPromptParts.push(toolCallMarkdown);
          currentInput = `Based on the user's query "${userInput}" and the information I have gathered so far (${augmentedPromptParts.join(' ')}), what should I do next?`;
          toolCalledDuringIteration = true;
          toolOutputAddedToPrompt = true;
        }
      } else if (currentIntent.event_type === 'earnings_request' && currentIntent.entities.some(e => e.type === 'STOCK_TICKER')) {
        // --- Tool Use Path: Fetch Earnings Data from SEC EDGAR API ---
        console.log('Agent loop: Detected an earnings request. Using SEC EDGAR API...');
        const tickerEntity = currentIntent.entities.find(e => e.type === 'STOCK_TICKER');
        if (tickerEntity) {
          const ticker = tickerEntity.value;
          const cik = await getCik(ticker);
          const startTime = new Date().getTime();
          const companyFacts = await fetchCompanyFacts(cik);
          const toolCallMarkdown = createToolCallMarkdown('fetchCompanyFacts', cik, startTime);
          allToolCalls.push({ toolName: 'fetchCompanyFacts', toolInput: cik, duration: (new Date().getTime() - startTime) });

          if (!cik) {
            augmentedPromptParts.push(`I could not find the CIK for ticker ${ticker}.`);
            augmentedPromptParts.push(toolCallMarkdown);
            toolCalledDuringIteration = true;
            toolOutputAddedToPrompt = true;
            // No further processing for earnings in this iteration if CIK is missing
          } else if (!companyFacts || !companyFacts.facts || !companyFacts.facts['us-gaap']) {
            augmentedPromptParts.push(`I could not retrieve company facts for ${ticker} (CIK: ${cik}).`);
            augmentedPromptParts.push(toolCallMarkdown);
            toolCalledDuringIteration = true;
            toolOutputAddedToPrompt = true;
            // No further processing for earnings in this iteration if facts are missing
          } else {
            contextForMemory.companyFacts = companyFacts;

            let fromDateTime = null;
            let toDateTime = null;

            const fromEntity = currentIntent.entities.find(e => e.type === 'DATE_FROM');
            const toEntity = currentIntent.entities.find(e => e.type === 'DATE_TO');

            if (fromEntity && toEntity) {
              const fromStr = fromEntity.value.substring(0, 8);
              const toStr = toEntity.value.substring(0, 8);
              fromDateTime = new Date(
                parseInt(fromStr.substring(0, 4)),
                parseInt(fromStr.substring(4, 6)) - 1,
                parseInt(fromStr.substring(6, 8))
              );
              toDateTime = new Date(
                parseInt(toStr.substring(0, 4)),
                parseInt(toStr.substring(4, 6)) - 1,
                parseInt(toStr.substring(6, 8))
              );
              console.log(`Agent loop: Filtering earnings from ${fromDateTime.toDateString()} to ${toDateTime.toDateString()}`);
            }

            const extractEpsData = (facts, isAnnual, fromFilter, toFilter) => {
              const epsData = [];
              if (!facts || !facts['us-gaap']) {
                return epsData;
              }

              const usGaap = facts['us-gaap'];

              const findMetricKeys = (needle) =>
                Object.keys(usGaap).filter((key) =>
                  key.toLowerCase().includes(needle)
                );

              const basicKeys = findMetricKeys('earningspersharebasic');
              const dilutedKeys = findMetricKeys('earningspersharediluted');

              const processUnitsArray = (unitsArray, isBasic) => {
                if (!Array.isArray(unitsArray)) return;
                unitsArray.forEach((unit) => {
                  if (!unit || !unit.form || !unit.end || unit.val === undefined) return;
                  const fiscalDate = new Date(unit.end);
                  const reportPrefix = isAnnual ? '10-K' : '10-Q';
                  if (!unit.form.startsWith(reportPrefix)) return;
                  if (fromFilter && fiscalDate < fromFilter) return;
                  if (toFilter && fiscalDate > toFilter) return;

                  const dateStr = fiscalDate.toISOString().split('T')[0];
                  let existingEntry = epsData.find(
                    (e) => e.date === dateStr && e.form === unit.form
                  );

                  if (!existingEntry) {
                    existingEntry = {
                      date: dateStr,
                      form: unit.form,
                      fy: unit.fy,
                      fp: unit.fp,
                    };
                    epsData.push(existingEntry);
                  }

                  if (isBasic) {
                    existingEntry.epsBasic = unit.val;
                  } else {
                    existingEntry.epsDiluted = unit.val;
                  }
                });
              };

              basicKeys.forEach((metricKey) => {
                const metric = usGaap[metricKey];
                if (!metric || !metric.units || typeof metric.units !== 'object') return;
                Object.keys(metric.units).forEach((unitName) => {
                  processUnitsArray(metric.units[unitName], true);
                });
              });

              dilutedKeys.forEach((metricKey) => {
                const metric = usGaap[metricKey];
                if (!metric || !metric.units || typeof metric.units !== 'object') return;
                Object.keys(metric.units).forEach((unitName) => {
                  processUnitsArray(metric.units[unitName], false);
                });
              });

              epsData.sort((a, b) => {
                if (b.fy !== a.fy) return b.fy - a.fy;
                const fpOrder = { 'Q4': 4, 'Q3': 3, 'Q2': 2, 'Q1': 1, 'FY': 5 };
                return (fpOrder[b.fp] || 0) - (fpOrder[a.fp] || 0);
              });
              return epsData;
            };

            let annualReports = extractEpsData(companyFacts.facts, true, fromDateTime, toDateTime);
            let quarterlyReports = extractEpsData(companyFacts.facts, false, fromDateTime, toDateTime);

            if (fromDateTime && toDateTime && annualReports.length === 0 && quarterlyReports.length === 0) {
              console.log('Agent loop: No earnings found strictly within requested window; falling back to most recent earnings data.');
              annualReports = extractEpsData(companyFacts.facts, true, null, null);
              quarterlyReports = extractEpsData(companyFacts.facts, false, null, null);
            }

            let annualEarningsSummary = 'No annual earnings data available for the specified period.';
            if (annualReports && annualReports.length > 0) {
              annualEarningsSummary = annualReports.slice(0, 3).map(report =>
                `Fiscal Year End: ${report.date} (FY: ${report.fy}), Basic EPS: ${report.epsBasic || 'N/A'}, Diluted EPS: ${report.epsDiluted || 'N/A'}`
              ).join('\n');
            }

            let quarterlyEarningsSummary = 'No quarterly earnings data available for the specified period.';
            if (quarterlyReports && quarterlyReports.length > 0) {
              quarterlyEarningsSummary = quarterlyReports.slice(0, 3).map(report =>
                `Fiscal Qtr End: ${report.date} (FY: ${report.fy}, FP: ${report.fp}), Basic EPS: ${report.epsBasic || 'N/A'}, Diluted EPS: ${report.epsDiluted || 'N/A'}`
              ).join('\n');
            }

            augmentedPromptParts.push(`Here is the earnings data for ${ticker} (CIK: ${cik}):\n--- Annual Earnings Reports ---\n${annualEarningsSummary}\n--- Quarterly Earnings Reports ---\n${quarterlyEarningsSummary}`);
            augmentedPromptParts.push(toolCallMarkdown);
            currentInput = `Based on the user's query "${userInput}" and the information I have gathered so far (${augmentedPromptParts.join(' ')}), what should I do next?`;
            toolCalledDuringIteration = true;
            toolOutputAddedToPrompt = true;
          }
        }
      } else if (currentIntent.event_type === 'filing_request' && currentIntent.entities.some(e => e.type === 'STOCK_TICKER')) {
        // --- Tool Use Path: Fetch SEC Filings from SEC EDGAR API ---
        console.log('Agent loop: Detected a filing request. Using SEC EDGAR API...');
        const tickerEntity = currentIntent.entities.find(e => e.type === 'STOCK_TICKER');
        if (tickerEntity) {
            const ticker = tickerEntity.value;
            const cik = await getCik(ticker);
            const startTime = new Date().getTime();
            const submissionMetadata = await fetchSubmissionMetadata(cik);
            const toolCallMarkdown = createToolCallMarkdown('fetchSubmissionMetadata', cik, startTime);
            allToolCalls.push({ toolName: 'fetchSubmissionMetadata', toolInput: cik, duration: (new Date().getTime() - startTime) });
            
            if (!cik) {
              augmentedPromptParts.push(`I could not find the CIK for ticker ${ticker}.`);
              augmentedPromptParts.push(toolCallMarkdown);
              toolCalledDuringIteration = true;
              toolOutputAddedToPrompt = true;
              // No further processing for filings in this iteration if CIK is missing
            } else if (!submissionMetadata || !submissionMetadata.filings || !submissionMetadata.filings.recent) {
              augmentedPromptParts.push(`I could not retrieve submission metadata for ${ticker} (CIK: ${cik}).`);
              augmentedPromptParts.push(toolCallMarkdown);
              toolCalledDuringIteration = true;
              toolOutputAddedToPrompt = true;
              // No further processing for filings in this iteration if metadata is missing
            } else {
              contextForMemory.submissionMetadata = submissionMetadata;

              const recentFilings = submissionMetadata.filings.recent;
              const filingForms = recentFilings.form;
              const accessionNumbers = recentFilings.accessionNumber;
              const reportDates = recentFilings.reportDate;

              const tenKFilings = [];
              const tenQFilings = [];
              let kCount = 0;
              let qCount = 0;

              for (let i = 0; i < filingForms.length && (kCount < 3 || qCount < 3); i++) {
                  const form = filingForms[i];
                  const accessionNumber = accessionNumbers[i];
                  const reportDate = reportDates[i];
                  
                  if (form === '10-K' && kCount < 3) {
                      tenKFilings.push({
                          reportDate: reportDate,
                          accessionNumber: accessionNumber,
                          form: form
                      });
                      kCount++;
                  } else if (form === '10-Q' && qCount < 3) {
                      tenQFilings.push({
                          reportDate: reportDate,
                          accessionNumber: accessionNumber,
                          form: form
                      });
                      qCount++;
                  }
              }

              const formatFilings = (filingList, type) => {
                if (!filingList || filingList.length === 0) {
                  return `No recent ${type} filings found.`;
                }
                return filingList.map(filing => {
                  const filingUrl = `https://www.sec.gov/Archives/edgar/data/${cik}/${filing.accessionNumber.replace(/-/g, '')}/${filing.accessionNumber}.txt`;
                  return `- ${type} filed on ${filing.reportDate} ([Link](${filingUrl}))`;
                }).join('\n');
              };

              const tenKSummary = formatFilings(tenKFilings, '10-K');
              const tenQSummary = formatFilings(tenQFilings, '10-Q');

              augmentedPromptParts.push(`Here are the most recent SEC filings for ${ticker} (CIK: ${cik}):\n--- 10-K Filings (Annual Reports) ---\n${tenKSummary}\n--- 10-Q Filings (Quarterly Reports) ---\n${tenQSummary}`);
              augmentedPromptParts.push(toolCallMarkdown);
              currentInput = `Based on the user's query "${userInput}" and the information I have gathered so far (${augmentedPromptParts.join(' ')}), what should I do next?`;
              toolCalledDuringIteration = true;
              toolOutputAddedToPrompt = true;
            }
          }
        }
        // If a tool was executed and output was added to prompt, we need to re-evaluate intent.
    } while (toolCalledDuringIteration && iterationCount < MAX_TOOL_ITERATIONS);


    // After the loop, generate the final response using all accumulated information.
    console.log(`Agent loop: Generating final response with accumulated prompt parts.`);
    const finalAugmentedPrompt = `${augmentedPromptParts.join('\n')}\n\nPlease summarize this information for the user, answering their original query: "${userInput}".`;
    const llmResponse = await generateResponse(finalAugmentedPrompt);
    console.log(`Agent loop: Received final response from LLM.`);

    // 6. Save to Memory: Prepare the data for the memory entry.
    const memoryEntryData = {
      user_input: userInput,
      llm_response: llmResponse,
      thematic_scope: currentIntent ? currentIntent.thematic_scope : 'unknown', // Use the last identified intent
      event_type: currentIntent ? currentIntent.event_type : 'no_tool_call', // Use the last identified event type
      entities: currentIntent ? currentIntent.entities : [], // Use the last identified entities
      context: contextForMemory // Save any data that was fetched from tools.
    };

    // 7. Persist Memory
    const addedEntry = appendMemory(memoryEntryData);
    if (!addedEntry) {
      throw new Error("Failed to append a valid memory entry. Check logs for details.");
    }
    await saveMemory();

    // 8. Return the final response and all tool calls to the UI.
    return { response: llmResponse, toolCall: allToolCalls.length > 0 ? allToolCalls[allToolCalls.length - 1] : null }; // Return the last tool call for now

  } catch (error) {
    console.error(`Agent Cycle Error: ${error.message}`);
    // Re-throw the error so it can be caught and handled by the entry point (e.e., index.js).
    throw error;
  } finally {
    console.log("Agent cycle finished.");
  }
}

// Export the updated runAgentCycle function.
module.exports = {
  runAgentCycle,
};